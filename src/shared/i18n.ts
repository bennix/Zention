const DICTS: Record<LocaleId, Record<MessageKey, string>> = {
  'zh-CN': zhCN,
  'zh-TW': zhTW,
  en,
  ja,
  ko,
  fr,
  de,
  es,
  pt,
  ru,
  ar,
  it,
}

export function normalizeLocale(value: string | undefined | null): LocaleId {
  return LOCALES.some((item) => item.id === value) ? (value as LocaleId) : 'zh-CN'
}

export function translate(locale: string | undefined, key: MessageKey, vars?: Record<string, string | number>): string {
  const table = DICTS[normalizeLocale(locale)]
  let text = table[key] ?? zhCN[key]
  if (!vars) return text
  for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value))
  return text
}
